const POWERS = POWER_CATALOG.map(([name, category, description, glyph, color, power, speed, defense]) => ({
  name, category, description, glyph, color,
  counterHint: COUNTER_HINTS[category] || 'Adapt your tactics to the situation.',
  stats: { power, speed, defense },
}));

function getPower(name) {
  return POWERS.find((power) => power.name === name) || {
    name, category: 'Unknown', description: 'A mysterious ability waiting to be defined.', glyph: '✦', color: '#8178FF', stats: { power: 1, speed: 1, defense: 1 },
  };
}

function summarizeAbilities(names = []) {
  const selected = names.map(getPower);
  if (!selected.length) return { power: 0, speed: 0, defense: 0, chaos: 0 };
  const sum = (key) => selected.reduce((total, ability) => total + ability.stats[key], 0);
  const sillyCount = selected.filter((ability) => ['Silly', 'Gross-Out', 'Chaos'].includes(ability.category)).length;
  return {
    power: Math.round(sum('power') / selected.length),
    speed: Math.round(sum('speed') / selected.length),
    defense: Math.round(sum('defense') / selected.length),
    chaos: Math.round((sillyCount / selected.length) * 5),
  };
}

module.exports = { POWERS, getPower, summarizeAbilities };
